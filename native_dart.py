"""Compile a site into Dart declarations and Flutter-native rendering code."""

import json
from pathlib import Path
import re
from native_frontend import load_site
from js_dart import quote


def generate(entry):
    site = load_site(entry)
    imports = []
    bodies = []
    for name in ["js_core", "dom", "css", "flutter"]:
        source = (Path(__file__).parent / "runtime" / f"{name}.dart").read_text(
            encoding="utf-8"
        )

        def collect(match):
            line = match[0]
            if "'dart:" in line or "'package:" in line:
                if line not in imports:
                    imports.append(line)
            return ""

        bodies.append(re.sub(r"^import .*;\n", collect, source, flags=re.M))
    imports.append("import 'package:shared_preferences/shared_preferences.dart';\n")
    data = {"entry": site.entry, "pages": site.pages, "assets": site.assets}
    source = (
        "// Generated by HTGC: native Dart code. No browser or JavaScript engine.\n"
        + "".join(imports)
        + "\n"
        + "".join(bodies)
    )
    source += "\n" + "".join(site.scripts)
    source += (
        "\nfinal Map<String,dynamic> htgcSiteData = jsonDecode("
        + quote(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
        + ");\n"
    )
    source += (
        "final List<void Function(JScope)> htgcScripts = ["
        + ",".join(f"htgcScript{i}" for i in range(len(site.scripts)))
        + "];\n"
    )
    source += """
Future<void> main(List<String> arguments) async {
  WidgetsFlutterBinding.ensureInitialized();
  final pages = Map<String, dynamic>.from(htgcSiteData['pages']);
  final String entry = arguments.isEmpty ? htgcSiteData['entry'] : arguments.first;
  if (!pages.containsKey(entry)) {
    throw ArgumentError('Page is not compiled: $entry');
  }
  final prefs = await SharedPreferences.getInstance();
  final saved = jsonDecode(prefs.getString('htgc.localStorage') ?? '{}');
  final storage = Map<String, String>.from(saved);
  runApp(NativeSiteApp(
    entry: entry,
    pages: pages,
    assets: Map<String, dynamic>.from(htgcSiteData['assets']),
    scripts: htgcScripts,
    storage: storage,
    saveStorage: (values) {
      prefs.setString('htgc.localStorage', jsonEncode(values));
    },
  ));
}
"""
    return source, site
