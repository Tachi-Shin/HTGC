// Run after npm --prefix javascript ci. Uses versions pinned by package-lock.json.
const fs = require('node:fs');
const path = require('node:path');
const {createRequire} = require('node:module');
const root = path.resolve(__dirname, '..');
const deps = createRequire(path.join(root, 'javascript/package.json'));
const read = file => fs.readFileSync(file, 'utf8').trim();
const license = read(deps.resolve('regenerate-unicode-properties/LICENSE-MIT.txt'));
const unicode = read(path.join(root, 'runtime/UNICODE-LICENSE.txt'));
const version = deps('regenerate-unicode-properties/unicode-version.js');
const lines = [
  "part of 'js_core.dart';", '',
  '// Generated by tools/generate_regexp_sets.cjs. Unicode ' + version,
  '/*', license, '', unicode, '*/', '',
  'const _emojiStringProperties = <String, (String, String)>{',
];
const names = deps('regenerate-unicode-properties').get('Property_of_Strings');
const all = new Set();
for (const name of names.filter(name => name !== 'RGI_Emoji')) {
  const {characters, strings} = deps('regenerate-unicode-properties/Property_of_Strings/' + name);
  const pattern = characters.toString({hasUnicodeFlag: true});
  lines.push("  '" + name + "': (r'" + pattern + "',");
  for (let i = 0; i < strings.length; i += 16) {
    const chunk = strings.slice(i, i + 16);
    if (chunk.some(s => /[\s']/.test(s))) throw Error('Unexpected emoji data');
    chunk.forEach(s => all.add(s));
    lines.push("    r'" + (i ? ' ' : '') + chunk.join(' ') + "'");
  }
  lines.push('  ),');
}
const rgi = deps('regenerate-unicode-properties/Property_of_Strings/RGI_Emoji');
if (rgi.strings.length !== all.size || rgi.strings.some(s => !all.has(s))) throw Error('Unexpected RGI union');
lines.push('};', '', '// Inclusive ranges with a constant simple-folding offset.', 'const _regexpFolds = <int>[');
const ranges = [];
for (const [from, to] of [...deps('regexpu-core/data/iu-foldings.js')].sort((a, b) => a[0]-b[0])) {
  const last = ranges.at(-1);
  if (last && last[1] + 1 === from && last[2] === to - from) last[1] = from;
  else ranges.push([from, from, to - from]);
}
for (let i = 0; i < ranges.length; i += 4) lines.push('  ' + ranges.slice(i, i + 4).flat().join(', ') + ',');
lines.push('];', '');
fs.writeFileSync(path.join(root, 'runtime/js_regexp_set_data.dart'), lines.join('\n'));
